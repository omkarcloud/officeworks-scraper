"""Cache TTL per /officeworks/* endpoint (cache.py, keyed on the validated
params; officeworks/api.py caches inside, tofler-style, so the sliced /
merged endpoints share one upstream fetch).

Officeworks reprices overnight and on Deals / Clearance windows (the
catalogue's priceDroppedStartDate / EndDate are whole dates), so prices are
cached for an hour; the catalogue record (name, specs, images, variants)
changes rarely and gets a day. Per-store stock is the one live signal and
is cached for 10 minutes only. Listings (Algolia) move with the same
nightly repricing, 1 h. Reviews / Q&A accrue slowly, 6 h. Reference data
(category tree, brands, stores) a day; the sitemaps (40k product URLs,
regenerated by the site daily) a day.
"""
from datetime import timedelta

PRODUCT_CACHE = timedelta(hours=24)       # the catalogue record, without price
PRICE_CACHE = timedelta(hours=1)          # /prices in cents, per SKU list
REVIEW_STATS_CACHE = timedelta(hours=6)   # Bazaarvoice averages / counts / distribution
AVAILABILITY_CACHE = timedelta(minutes=10)
LISTING_CACHE = timedelta(hours=1)        # search / category / brand / specials pages
SUGGESTIONS_CACHE = timedelta(hours=12)
REVIEWS_CACHE = timedelta(hours=6)
QUESTIONS_CACHE = timedelta(hours=6)
CATEGORIES_CACHE = timedelta(hours=24)
BRANDS_CACHE = timedelta(hours=24)
STORES_CACHE = timedelta(hours=24)
STORES_SEARCH_CACHE = timedelta(hours=24)
LOCATIONS_CACHE = timedelta(hours=24)
SITEMAP_CACHE = timedelta(hours=24)       # one row per sitemap, sliced per page
